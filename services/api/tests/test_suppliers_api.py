def test_currency_must_match_country(client: TestClient) -> None:
    """CONTEXT § Business constraints: USA→USD, Spain→EUR."""
    r = client.post("/suppliers", json={**VALID, "country": "USA"})  # still EUR
    assert r.status_code == 422
    assert "currency" in json.dumps(r.json()).lower()

    ok = client.post(
        "/suppliers",
        json={**VALID, "name": "US Co", "country": "USA", "currency": "USD"},
    )
    assert ok.status_code == 201


def test_dual_category_carrier_is_valid(client: TestClient) -> None:
    """CONTEXT: a carrier may be both last-mile and international."""
    r = client.post(
        "/suppliers",
        json={
            **VALID,
            "name": "DHL Test",
            "categories": ["carrier_last_mile", "carrier_international"],
        },
    )
    assert r.status_code == 201
    assert r.json()["categories"] == ["carrier_last_mile", "carrier_international"]


def test_all_eight_context_categories_are_accepted(client: TestClient) -> None:
    categories = [
        "carrier_last_mile",
        "carrier_international",
        "warehouse_supplies",
        "packaging_materials",
        "reverse_logistics",
        "fleet_maintenance",
        "it_and_wms_software",
        "cleaning_and_facilities",
    ]
    for i, category in enumerate(categories):
        r = client.post(
            "/suppliers",
            json={**VALID, "name": f"Supplier {i}", "categories": [category]},
        )
        assert r.status_code == 201, f"{category} rejected"


