def test_data_survives_a_server_restart(
    client: TestClient, tmp_path: Path
) -> None:
    """Cross-cutting: TinyDB persists — data is still there after a restart."""
    client.post("/suppliers", json=VALID)

    # It is really on disk, not just in memory.
    raw = json.loads((tmp_path / "test.json").read_text(encoding="utf-8"))
    assert any(
        row["name"] == "Correos Express" for row in raw["suppliers"].values()
    )

    # Simulate a restart: close the handle, build a fresh app + client.
    import database

    database.close_db()

    from main import app

    with TestClient(app) as fresh:
        names = {s["name"] for s in fresh.get("/suppliers").json()}
    assert "Correos Express" in names
