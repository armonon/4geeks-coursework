def test_create_returns_complete_object_with_id(client: TestClient) -> None:
    r = client.post("/suppliers", json=VALID)
    assert r.status_code == 201
    body = r.json()
    assert body["id"] >= 1
    assert body["name"] == "Correos Express"
    assert body["country"] == "Spain"
    assert body["categories"] == ["carrier_last_mile"]
    assert body["rate_per_shipment"] == 4.10
    assert body["currency"] == "EUR"
    assert body["status"] == "active"
    # updated_at is system-generated, never sent by the client.
    assert body.get("updated_at")


def test_updated_at_is_ignored_if_client_sends_it(client: TestClient) -> None:
    """CONTEXT: updated_at is generated by the system, not the client."""
    r = client.post(
        "/suppliers", json={**VALID, "updated_at": "1999-01-01T00:00:00+00:00"}
    )
    assert r.status_code == 201
    assert not r.json()["updated_at"].startswith("1999")


